import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from google.colab import drive
drive.mount('/content/drive')

df=pd.read_excel('/content/Bookings-100000-Rows.xlsx')

df.head()

# Replacing text 'null' with actual missing values (NaN)
df.replace("null", np.nan, inplace=True)

print("Null string replaced with NaN values")

# Converting to datetime formats
df['Date'] = pd.to_datetime(df['Date'])
df['Time'] = pd.to_datetime(df['Time'], errors='coerce').dt.time

print("Date and Time formats converted successfully")

# Converting columns to numeric types for analysis
df['Driver_Ratings'] = pd.to_numeric(df['Driver_Ratings'])
df['Customer_Rating'] = pd.to_numeric(df['Customer_Rating'])
df['Booking_Value'] = pd.to_numeric(df['Booking_Value'])
df['Ride_Distance'] = pd.to_numeric(df['Ride_Distance'])

print("Ratings and Values converted to numeric type")

# Saving the cleaned data into a new CSV file
df.to_csv("cleaned_ride_bookings.csv", index=False)

print("Cleaned file saved as 'cleaned_ride_bookings.csv'")

# 1. Ride Status Distribution
plt.figure(figsize=(8,5))
sns.set_theme(style="whitegrid")
sns.countplot(data=df, x='Booking_Status', order=df['Booking_Status'].value_counts().index)
plt.title('Ride Booking Status Distribution')
plt.xticks(rotation=45)
plt.tight_layout()
plt.savefig('booking_status.png')
plt.show()

# 2. Revenue by Vehicle Type
plt.figure(figsize=(8,5))
sns.set_theme(style="whitegrid")
revenue = df.groupby('Vehicle_Type')['Booking_Value'].sum().sort_values(ascending=False).reset_index()
sns.barplot(data=revenue, x='Vehicle_Type', y='Booking_Value')
plt.title('Total Revenue by Vehicle Type')
plt.tight_layout()
plt.savefig('revenue_by_vehicle.png')
plt.show()

